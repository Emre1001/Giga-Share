export const LANGS = { en, de, tr } as const;
export type Lang = keyof typeof LANGS;
export type LangSetting = Lang | "system";
export const LANG_NAMES: Record<Lang, string> = { en: "English", de: "Deutsch", tr: "Türkçe" };

/** First supported language from the OS/browser preference list, else English. */
export function systemLang(): Lang {
  for (const l of navigator.languages ?? [navigator.language]) {
    const code = l.slice(0, 2).toLowerCase();
    if (code in LANGS) return code as Lang;
  }
  return "en";
}

export const resolveLang = (s: LangSetting): Lang => (s === "system" ? systemLang() : s);

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  return (key, vars) => {
    let s = LANGS[lang][key] ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    // "(s)" style plurals: drop the marker for 1, keep the bare plural otherwise.
    if (vars && "n" in vars) s = Number(vars.n) === 1 ? s.replace(/\((e|s|en)\)/g, "") : s.replace(/\((e|s|en)\)/g, "$1");
    return s;
  };
}

const Ctx = createContext<{ t: T; lang: Lang }>({ t: makeT("en"), lang: "en" });
export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  const value = useMemo(() => ({ t: makeT(lang), lang }), [lang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}
export const useT = () => useContext(Ctx);
